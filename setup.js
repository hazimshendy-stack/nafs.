"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = process.cwd();
const log = (m) => console.log("  ✓ " + m);
const warn = (m) => console.log("  ! " + m);

function mkdirp(p) {
  fs.mkdirSync(path.join(ROOT, p), { recursive: true });
}

function writeFile(rel, content, { overwrite = false } = {}) {
  const full = path.join(ROOT, rel);
  mkdirp(path.dirname(rel));
  if (fs.existsSync(full) && !overwrite) {
    const cur = fs.readFileSync(full, "utf8");
    if (cur === content) {
      warn("لم يتغير: " + rel);
      return;
    }
    const backup = full + ".bak";
    fs.writeFileSync(backup, cur);
    warn("نسخة احتياطية: " + rel + " → " + path.basename(backup));
  }
  fs.writeFileSync(full, content, "utf8");
  log(rel);
}

